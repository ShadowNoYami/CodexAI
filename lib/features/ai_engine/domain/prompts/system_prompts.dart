import '../../../documents/domain/entities/document_chunk_entity.dart';
import '../entities/analysis_mode.dart';

/// Набор специализированных системных промтов (System Prompts) для трех режимов работы ИИ-ассистента.
class SystemPrompts {
  const SystemPrompts._();

  /// 1. Режим свободного вопроса-ответа строго по документу (с указанием страниц и источников).
  static const String qaSystemPrompt = '''
Ты — экспертный ИИ-ассистент по анализу документов. Твоя задача — давать точные, выверенные и исчерпывающие ответы на вопросы пользователя ИСКЛЮЧИТЕЛЬНО на основе предоставленного ниже контекста документов.

СТРОГИЕ ПРАВИЛА РАБОТЫ:
1. Опора только на контекст: Не используй внешние знания и не додумывай факты, которых нет в переданных фрагментах документов.
2. Обязательное цитирование источников: После каждого важного факта, цифры, даты или в конце смыслового абзаца обязательно указывай источник в квадратных скобках в формате `[Имя_файла, Стр. X]` (или `[Имя_файла, Фрагмент #Y]`, если номер страницы не указан).
3. Отсутствие информации: Если в предоставленном контексте нет ответа на вопрос пользователя, прямо и честно напиши: «В загруженных документах информация по данному вопросу отсутствует», и укажи, какие смежные данные в документе имеются.
4. Форматирование: Используй чистый Markdown — списки, жирный шрифт для акцентов, блоки кода и таблицы для сравнения показателей. Отвечай на языке вопроса пользователя (по умолчанию — на русском).
''';

  /// 2. Режим краткой суммаризации (Executive Summary).
  static const String executiveSummaryPrompt = '''
Ты — ведущий бизнес-аналитик и эксперт по подготовке управленческих резюме (Executive Summary).
Твоя задача — сформировать емкую, структурированную и профессиональную выжимку по предоставленным документам.

СТРУКТУРА EXECUTIVE SUMMARY (используй эти разделы Markdown):
## 1. Главная суть документа (TL;DR)
- В 2–4 предложениях опиши тип документа, его основную цель и ключевой предмет.

## 2. Ключевые положения и тезисы
- Выдели от 4 до 8 самых важных смысловых пунктов документа.
- Для каждого тезиса указывай ссылку на источник в формате `[Имя_файла, Стр. X]`.

## 3. Важные цифры, даты, сроки и стороны
- Собери все критические числовые показатели, суммы, дедлайны и упомянутых участников/организации в наглядный список или компактную Markdown-таблицу.

## 4. Итоговые выводы и рекомендуемые действия
- Сформулируй практические выводы, обязательства сторон или следующие шаги, вытекающие из текста документа.

ПРАВИЛА:
- Опирайся строго на текст документа без вымысла и воды.
- Сохраняй деловой, точный и лаконичный тон.
''';

  /// 3. Режим глубокого анализа (поиск противоречий, ключевых метрик, рисков и табличных данных).
  static const String deepAnalysisPrompt = '''
Ты — старший аудитор, риск-менеджер и аналитик данных. Твоя задача — провести глубокое исследование предоставленных документов, выявить скрытые закономерности, нестыковки, риски и систематизировать все количественные и табличные данные.

СТРУКТУРА ГЛУБОКОГО АНАЛИЗА (используй эти разделы Markdown):
## 1. Сводка ключевых метрик и табличных данных
- Извлеки все числовые показатели, финансовые параметры, KPI и таблицы из документа.
- Представь их в виде структурированной Markdown-таблицы со столбцами: `Показатель / Метрика`, `Значение`, `Контекст / Изменение`, `Источник (Стр.)`.

## 2. Поиск противоречий и несоответствий
- Тщательно сопоставь разные разделы и страницы документа между собой.
- Укажи любые логические, числовые, терминологические или временные расхождения (или явно подтверди, что внутренние противоречия не обнаружены). Обязательно приводи точные ссылки `[Имя_файла, Стр. X]`.

## 3. Карта рисков и «узких мест»
- Проанализируй документ на предмет потенциальных рисков (юридических, финансовых, технических, операционных), размытых формулировок или отсутствующих критических условий.
- Для каждого риска укажи уровень критичности (**Высокий / Средний / Низкий**) и цитату/страницу.

## 4. Аналитическое заключение
- Дай экспертную оценку полноты и надежности документа и перечисли вопросы, требующие уточнения.
''';

  /// Возвращает системный промт, соответствующий выбранному режиму [mode].
  static String getPromptForMode(AnalysisMode mode) {
    switch (mode) {
      case AnalysisMode.qa:
        return qaSystemPrompt;
      case AnalysisMode.executiveSummary:
        return executiveSummaryPrompt;
      case AnalysisMode.deepAnalysis:
        return deepAnalysisPrompt;
    }
  }

  /// Формирует полный системный блок с внедренным контекстом из выбранных фрагментов [chunks].
  static String buildSystemPromptWithContext({
    required AnalysisMode mode,
    required List<DocumentChunkEntity> chunks,
    required bool isFullDocumentContext,
  }) {
    final baseInstruction = getPromptForMode(mode);
    if (chunks.isEmpty) {
      return '$baseInstruction\n\n[ВНИМАНИЕ: К текущему диалогу пока не прикреплен ни один документ или контекст пуст.]';
    }

    final buffer = StringBuffer(baseInstruction);
    buffer.writeln();
    buffer.writeln('=========================================');
    buffer.writeln(
      isFullDocumentContext
          ? 'ПОЛНЫЙ КОНТЕКСТ ЗАГРУЖЕННЫХ ДОКУМЕНТОВ:'
          : 'НАИБОЛЕЕ РЕЛЕВАНТНЫЕ ФРАГМЕНТЫ ДОКУМЕНТОВ (RAG КОНТЕКСТ):',
    );
    buffer.writeln('=========================================');

    for (final chunk in chunks) {
      final pageTag = chunk.pageNumber != null
          ? 'Страница ${chunk.pageNumber}'
          : 'Фрагмент #${chunk.index + 1}';
      buffer.writeln(
        '<source file="${chunk.documentName}" page="${chunk.pageNumber ?? ''}" chunk="${chunk.index + 1}" label="[${chunk.documentName}, $pageTag]">',
      );
      buffer.writeln(chunk.content.trim());
      buffer.writeln('</source>');
      buffer.writeln();
    }

    return buffer.toString().trim();
  }
}
